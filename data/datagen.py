#!/usr/bin/env python3
"""Build the game's static data tables from the YAML files in data/.

Usage:
    datagen.py OUTDIR       write dataids.h and data_tables.c into OUTDIR

Each YAML file is a list of entries, one per element of a C array (a list
of lists for a two-dimensional one). An entry is written out as a C
designated initializer: its keys are the struct's field names and its
values are C values.

    - name: iengineFuelMizer        # its enum value in dataids.h
      szName: "Fuel Mizer"          # sz keys are strings (UTF-8)
      rgwtOreCost: [8]              # lists become {8}
      grfAbilities: engineFuelMizer # other strings are C expressions
      hul: {...}                    # maps become nested initializers

Two more forms follow the Hungarian prefixes:

      rgAttr: {rsResGen: 10}        # an rg map sets elements: {[rsResGen] = 10}
      grbitAttr: [grbitRaceIFE, grbitRaceTT]   # a grbit or grf list is ORed

The compiler checks the field names, enum values and types, so this script
knows nothing of the structs. Fields left out are zero. Only keys starting
with f may hold true/false, and a string too long for its sz field fails a
static assertion. Only tables that define an enum have a name per entry.

An entry's position in its file is its enum value. Code uses the names, but
saved ship designs store hull and part numbers, so the parts files are
append-only: reordering or removing an entry would load 2.6j and 2.8 designs
with the wrong parts. The regression's checkpoints hold such designs and
would show it. Code that uses a renamed entry's old name no longer compiles.

Fields the generator fills in, which the YAML must not set:
    id           COMPART tables: the position + 1
    hul.ihuldef  hulls: the hull's HulDef
    hul.chs      the number of hul.rghs slots
    iplan        battle plans: the position
"""

import os
