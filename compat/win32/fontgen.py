#!/usr/bin/env python3
"""Embed the checksum-pinned, unmodified Liberation font faces for SDL builds."""
import hashlib
import json
from pathlib import Path
import sys

source, destination = map(Path, sys.argv[1:])
origin = json.loads((source / 'ORIGIN.json').read_text())
expected = [f'Liberation{family}-{style}.ttf'
            for family in ('Sans', 'Serif', 'Mono')
            for style in ('Regular', 'Bold', 'Italic', 'BoldItalic')]
if [row['file'] for row in origin['fonts']] != expected:
    raise SystemExit('Font table order must match the fixed family/style map')
lines = ['/* Generated by compat/win32/fontgen.py; fonts retain their SIL OFL license. */',
         '#include "internal.h"']
rows = []
for i, row in enumerate(origin['fonts']):
    data = (source / row['file']).read_bytes()
    if len(data) != row['size'] or hashlib.sha256(data).hexdigest() != row['sha256']:
        raise SystemExit(f"Font checksum mismatch: {row['file']}")
    lines.append(f'static constinit const BYTE rgbFont{i}[] = {{')
    for offset in range(0, len(data), 32):
        lines.append('    ' + ','.join(f'0x{b:02x}' for b in data[offset:offset + 32]) + ',')
    lines.append('};')
    rows.append(f'    {{rgbFont{i}, sizeof(rgbFont{i})}},')
lines.append('constinit const COMPATFONTDATA rgCompatFontData[12] = {')
lines.extend(rows)
lines.append('};')
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text('\n'.join(lines) + '\n')
