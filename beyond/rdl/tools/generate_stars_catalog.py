#!/usr/bin/env python3
"""Export queryable catalog/starting-template facts; requires repository PyYAML.

Trait gates are maintained in rules/equipment.rdl, not inferred from prose.
"""
import argparse
import json
from pathlib import Path
import sys
import yaml

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parents[1] / 'examples/stars/catalog.rdl'
TABLES = [('hulls','hull'),('starbase-hulls','base_hull'),('engines','engine'),('armor','armor'),('scanners','scanner'),('shields','shield'),('electrical','electrical'),('mechanical','mechanical'),('mine-layers','mine'),('mining-robots','mining'),('planetary','planetary'),('terraformers','terra'),('bombs','bomb'),('torpedoes','torpedo'),('beams','beam'),('starbase-specials','base_special')]
FIELDS = ['energy','weapons','propulsion','construction','electronics','biotechnology']
HST = dict(zip(['hstHull','hstSBHull','hstEngine','hstArmor','hstScanner','hstShield','hstSpecialE','hstSpecialM','hstMines','hstMining','hstPlanetary','hstTerra','hstBomb','hstTorp','hstBeam','hstSpecialSB'], [x[1] for x in TABLES]))


def vector(vals):
    vals = (vals + [0]*6)[:6]
    return '{ ' + ' '.join(f'{k} = {v};' for k,v in zip(FIELDS,vals)) + ' }'


def generate():
    text = '''(* Generated by tools/generate_stars_catalog.py from data/parts/*.yaml.
   Stable source symbols identify parts; indexes retain the source enum order. *)
import stars.rules.equipment

'''
    tables = {name: yaml.safe_load((ROOT/f'data/parts/{name}.yaml').read_text()) for name,_ in TABLES}
    for name, category in TABLES:
        for i,row in enumerate(tables[name]):
            data = row.get('hul', row)
            costs = (data.get('rgwtOreCost',[]) + [0]*3)[:3]
            text += f'CatalogPart part_{row["name"]} = {{\n'
            for key,value in [('symbol',row['name']),('name',data.get('szName', data.get('szClass',''))),('category',category),('index',i),('requirements',None),('ironium',costs[0]),('boranium',costs[1]),('germanium',costs[2]),('resources',data.get('resCost',0))]:
                value = vector(data.get('rgTech',[])) if key=='requirements' else json.dumps(value, ensure_ascii=False)
                text += f'  {key} = {value};\n'
            text += '}\n'
    for filename,base in [('starting-ships',False),('starting-starbases',True)]:
        for i,row in enumerate(yaml.safe_load((ROOT/f'data/parts/{filename}.yaml').read_text())):
            data=row['hul']
            hull=data.get('ihuldef','ihuldefSmallFreighter')
            if 'ihuldef' not in data: assert not base
            text += f'StartingTemplate template_{filename.replace("-","_")}_{i} = {{\n'
            text += f'  index = {i}; starbase = {str(base).lower()}; name = {json.dumps(data["szClass"], ensure_ascii=False)}; hull = {json.dumps(hull)};\n'
            text += '  slots = {\n'
            for j,slot in enumerate(data.get('rghs',[])):
                text += f'    {{ slot = {j}; category = {json.dumps(HST.get(slot["grhst"], slot["grhst"]))}; part_index = {slot.get("iItem",0)}; quantity = {slot.get("cItem",0)}; }};\n'
            text += '  };\n}\n'
    return text


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    text=generate()
    if args.check:
        if not OUT.exists() or OUT.read_text()!=text: sys.exit(f'Stale generated catalog: {OUT}')
    else: OUT.write_text(text)


if __name__=='__main__': main()
